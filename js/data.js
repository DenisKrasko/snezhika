(function check () {
  if (typeof window === 'undefined' || location.search.indexOf('check') < 0) return;
  const D = window.DATA, out = [];
  const codes = new Set(D.suppliers.map((s) => s.code));
  if (codes.size !== D.suppliers.length) out.push('дубли кодов поставщиков');
  const arts = new Set(D.goods.map((g) => g.art));
  if (arts.size !== D.goods.length) out.push('дубли артикулов');
  const cats = new Set(D.categories);
  D.suppliers.forEach((s) => { if (!cats.has(s.cat)) out.push('поставщик ' + s.code + ': категория «' + s.cat + '» вне справочника'); });
  D.goods.forEach((g) => {
    if (!codes.has(g.sup)) out.push('товар ' + g.art + ': нет поставщика ' + g.sup);
    if (!cats.has(g.cat)) out.push('товар ' + g.art + ': категория «' + g.cat + '» вне справочника');
  });
  const ids = new Set(D.orders.map((o) => o.id));
  if (ids.size !== D.orders.length) out.push('дубли номеров заказов');
  const st = new Set(D.orderStatuses);
  D.orders.forEach((o) => {
    if (!codes.has(o.sup)) out.push('заказ ' + o.id + ': нет поставщика ' + o.sup);
    if (!st.has(o.status)) out.push('заказ ' + o.id + ': статус «' + o.status + '» вне справочника');
    const qty = o.pos.reduce((a, p) => a + p.qty, 0);
    const sum = o.pos.reduce((a, p) => a + p.qty * p.price, 0);
    if (qty !== o.items) out.push('заказ ' + o.id + ': позиций ' + o.items + ', в строках ' + qty);
    if (sum !== o.sum) out.push('заказ ' + o.id + ': сумма ' + o.sum + ', в строках ' + sum);
  });
  const tabs = new Set(D.collectionTabs);
  Object.keys(D.collections).forEach((tab) => {
    if (!tabs.has(tab)) out.push('лишний таб сборов «' + tab + '»');
    D.collections[tab].forEach((c) => { if (!codes.has(c.sup)) out.push('сбор ' + c.id + ': нет поставщика ' + c.sup); });
  });
  D.balance.movements.forEach((m) => { if (m.ref && !ids.has(m.ref)) out.push('движение ' + m.date + ': заказ ' + m.ref + ' не найден'); });
  console.log(out.length ? 'ПРОВЕРКА: ' + out.join(' | ') : 'OK');
})();
